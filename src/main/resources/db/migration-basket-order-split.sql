-- Migration: split unified baskets table into baskets (cart) + orders + order_items + payments
-- Run once against seconddb. Safe to re-run (IF NOT EXISTS + guarded inserts).
-- Matches JPA entities in ir.linuxian.second.entities.shopping.{basket,order} + payment.

-- 1) New tables -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(255) NOT NULL UNIQUE,
    access_token VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT REFERENCES users(id),
    status VARCHAR(255) NOT NULL,
    total_amount NUMERIC(38,2) NOT NULL,
    customer_name VARCHAR(255),
    customer_phone VARCHAR(255),
    customer_address VARCHAR(255),
    customer_email VARCHAR(255),
    paid_ref_id VARCHAR(255),
    ordered_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name VARCHAR(255) NOT NULL,
    unit_price NUMERIC(38,2) NOT NULL,
    quantity INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    authority VARCHAR(255) NOT NULL UNIQUE,
    amount NUMERIC(38,2) NOT NULL,
    status VARCHAR(255) NOT NULL,
    ref_id BIGINT,
    card_pan VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- 2) Migrate old orders (baskets with status != OPEN) ------------------------
-- Old statuses: ORDERED, CONFIRMED, SHIPPED, DELIVERED, CANCELLED
-- New OrderStatus: PENDING_PAYMENT, PAID, PROCESSING, SHIPPED, DELIVERED, CANCELLED, PAYMENT_FAILED, REFUNDED
-- Old ORDERED/CONFIRMED (placed, stock decremented, no gateway) -> PROCESSING (implicitly paid).
INSERT INTO orders (order_number, access_token, user_id, status, total_amount,
                    customer_name, customer_phone, customer_address, customer_email,
                    paid_ref_id, ordered_at, created_at, updated_at)
SELECT
    COALESCE(NULLIF(b.order_number, ''),
             'ORD-' || b.id || '-' || UPPER(TO_HEX((EXTRACT(EPOCH FROM COALESCE(b.ordered_at, b.created_at)) * 1000)::BIGINT))),
    md5(random()::text || clock_timestamp()::text || b.id::text),
    b.user_id,
    CASE b.status
        WHEN 'SHIPPED' THEN 'SHIPPED'
        WHEN 'DELIVERED' THEN 'DELIVERED'
        WHEN 'CANCELLED' THEN 'CANCELLED'
        ELSE 'PROCESSING'
    END,
    COALESCE(b.total, 0),
    b.customer_name,
    b.customer_phone,
    b.customer_address,
    NULL,
    NULL,
    COALESCE(b.ordered_at, b.created_at, NOW()),
    b.created_at,
    COALESCE(b.updated_at, b.created_at, NOW())
FROM baskets b
WHERE b.status IS DISTINCT FROM 'OPEN'
  AND NOT EXISTS (SELECT 1 FROM orders o WHERE o.order_number = b.order_number AND b.order_number IS NOT NULL AND b.order_number <> '')
  AND NOT EXISTS (SELECT 1 FROM orders o JOIN baskets bb ON bb.id = b.id WHERE o.created_at = bb.created_at AND o.total_amount = COALESCE(bb.total,0) AND o.user_id IS NOT DISTINCT FROM bb.user_id);
-- Note: second NOT EXISTS guards the NULL-order_number row (basket id=2) from double-insert on re-run.
-- Re-run safety for NULL order_numbers: check by basket linkage via created_at+total+user (good enough for 2 rows).
-- If duplicates ever occur, the UNIQUE(order_number) will fail loudly rather than silently duplicating.

-- Fix the corner case where the same basket was inserted twice with different access_tokens:
-- (no-op if migration ran once).

-- 3) Migrate items: basket_items of old orders -> order_items (price snapshot) --
INSERT INTO order_items (order_id, product_id, product_name, unit_price, quantity)
SELECT o.id, bi.product_id, p.name,
       ROUND(COALESCE(p.price, 0) * (100 - COALESCE(p.discount_percent, 0)) / 100.0),
       bi.qty
FROM basket_items bi
JOIN baskets b ON b.id = bi.basket_id
JOIN products p ON p.id = bi.product_id
JOIN orders o ON (
    (b.order_number IS NOT NULL AND b.order_number <> '' AND o.order_number = b.order_number)
    OR
    (b.order_number IS NULL OR b.order_number = '')
        AND o.user_id IS NOT DISTINCT FROM b.user_id
        AND o.total_amount = COALESCE(b.total, 0)
        AND o.created_at = b.created_at
)
WHERE b.status IS DISTINCT FROM 'OPEN'
  AND NOT EXISTS (SELECT 1 FROM order_items oi WHERE oi.order_id = o.id AND oi.product_id = bi.product_id);

-- 4) Freeze old baskets as checked-out ---------------------------------------
UPDATE baskets SET status = 'CHECKED_OUT' WHERE status IS DISTINCT FROM 'OPEN' AND status <> 'CHECKED_OUT';

-- 5) Drop order columns from baskets (now owned by orders) -------------------
-- Hibernate ddl-auto=update never drops columns, so do it explicitly.
ALTER TABLE baskets DROP COLUMN IF EXISTS customer_name;
ALTER TABLE baskets DROP COLUMN IF EXISTS customer_phone;
ALTER TABLE baskets DROP COLUMN IF EXISTS customer_address;
ALTER TABLE baskets DROP COLUMN IF EXISTS order_number;
ALTER TABLE baskets DROP COLUMN IF EXISTS ordered_at;
ALTER TABLE baskets DROP COLUMN IF EXISTS total;

