-- Telegram book upload feature.
-- Run once against seconddb if you prefer to create the schema by hand;
-- Hibernate ddl-auto=update also adds these objects from the JPA entities.
-- Safe to re-run.

ALTER TABLE books ADD COLUMN IF NOT EXISTS uploaded BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS books_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    chat_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_books_messages_book_id ON books_messages(book_id);
